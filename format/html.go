type HTMLFormatter struct{}

func NewHTMLFormatter() *HTMLFormatter { return &HTMLFormatter{} }

var htmlSeverityOrder = []reportx.Severity{
	reportx.SeverityCritical,
	reportx.SeverityHigh,
	reportx.SeverityMedium,
	reportx.SeverityLow,
	reportx.SeverityInfo,
}

var htmlSeverityColors = map[reportx.Severity]string{
	reportx.SeverityCritical: "#d32f2f",
	reportx.SeverityHigh:     "#f57c00",
	reportx.SeverityMedium:   "#f9a825",
	reportx.SeverityLow:      "#1976d2",
	reportx.SeverityInfo:     "#616161",
}

